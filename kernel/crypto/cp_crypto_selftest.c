#include "provider.h"
#include <string.h>

void cp_crypto_selftest(void)
{
    static const unsigned char key[16] = {
        0x00,0x01,0x02,0x03,0x04,0x05,0x06,0x07,
        0x08,0x09,0x0a,0x0b,0x0c,0x0d,0x0e,0x0f};
    static const unsigned char plain[16] = {
        0x00,0x11,0x22,0x33,0x44,0x55,0x66,0x77,
        0x88,0x99,0xaa,0xbb,0xcc,0xdd,0xee,0xff};
    static const unsigned char cipher[16] = {
        0x69,0xc4,0xe0,0xd8,0x6a,0x7b,0x04,0x30,
        0xd8,0xcd,0xb7,0x80,0x70,0xb4,0xc5,0x5a};
    static const unsigned char sha256_empty[32] = {
        0xe3,0xb0,0xc4,0x42,0x98,0xfc,0x1c,0x14,
        0x9a,0xfb,0xf4,0xc8,0x99,0x6f,0xb9,0x24,
        0x27,0xae,0x41,0xe4,0x64,0x9b,0x93,0x4c,
        0xa4,0x95,0x99,0x1b,0x78,0x52,0xb8,0x55};
    unsigned char output[32];
    ccecb_ctx_decl(cp_aes_ecb_enc.size, aes);
    cp_aes_ecb_enc.init(&cp_aes_ecb_enc, aes, sizeof(key), key);
    cp_aes_ecb_enc.ecb(aes, 1, plain, output);
    if (memcmp(output, cipher, sizeof(cipher)))
        cp_crypto_fail("AES startup self-test failed");
    ccdigest_di_decl(&cp_sha256, hash);
    ccdigest_init(&cp_sha256, hash);
    cp_sha256.final(&cp_sha256, hash, output);
    if (memcmp(output, sha256_empty, sizeof(sha256_empty)))
        cp_crypto_fail("SHA-256 startup self-test failed");
    cc_clear(sizeof(output), output);
    ccecb_ctx_clear(cp_aes_ecb_enc.size, aes);
    ccdigest_di_clear(&cp_sha256, hash);
}
