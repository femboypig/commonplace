#!/usr/bin/env python3
"""Build Apple's native IPConfiguration bundle and Mach command client."""

import plistlib
import shutil
import subprocess
from darwin_build import ROOT, OUT, LD, archive, compile_source, link_program, prepare_source
from mach_interface import generate_interface

BOOTPLIB = (
    'arp.c',
    'bootp_transmit.c',
    'bpflib.c',
    'bsdplib.c',
    'cfutil.c',
    'dhcp_options.c',
    'dhcplib.c',
    'DNSNameList.c',
    'dynarray.c',
    'host_identifier.c',
    'hostlist.c',
    'in_cksum.c',
    'inetroute.c',
    'interfaces.c',
    'ioregpath.c',
    'macnc_options.c',
    'nbimages.c',
    'nbsp.c',
    'netinfo.c',
    'NICache.c',
    'IPConfigurationControlPrefs.c',
    'ptrlist.c',
    'subnets.c',
    'util.c',
    'IPv4ClasslessRoute.c',
    'IPConfigurationLog.c',
    'DHCPDUID.c',
    'DHCPv6.c',
    'DHCPv6Options.c',
)
PLUGIN = (
    'arp_session.c',
    'bootp.c',
    'bootp_session.c',
    'dhcp.c',
    'ipconfigd.c',
    'linklocal.c',
    'manual.c',
    'server.c',
    'timer.c',
    'failover.c',
    'DHCPLease.c',
    'HostUUID.c',
    'ifutil.c',
    'rtutil.c',
    'sysconfig.c',
    'rtadv.c',
    'manual_v6.c',
    'DHCPv6Client.c',
    'IPv6Socket.c',
    'DHCPv6Socket.c',
    'linklocal_v6.c',
    'DHCPDUIDIAID.c',
    'RTADVSocket.c',
)


def main():
    source = prepare_source("bootp")
    generated = OUT / "ipconfiguration"
    interface = generate_interface("ipconfig", source / "bootplib/ipconfig.defs",
        generated, arch="x86_64", defines=("__LP64__",))
    # This is the header generated by Apple's RC_RELEASE=Darwin build phase.
    (generated / "my_darwin.h").write_text("#define NO_WIRELESS\n")
    include = OUT / "include/ipconfiguration"
    for name in ("net/firewire.h", "netinet6/ip6_var.h"):
        target = include / name
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(ROOT / "sources/xnu/bsd" / name, target)
    bsm = prepare_source("openbsm", "openbsm")
    flags = [
        "-fblocks", "-DPRIVATE", "-DDEPLOYMENT_TARGET_MACOSX=1",
        "-D__APPLE_USE_RFC_3542", "-DHAVE_OS_ACTIVITY=0",
        "-DHAVE_POWERD=0", "-DHAVE_CGA=0", "-DHAVE_USER_NOTIFICATIONS=0",
        "-DHAVE_6TO4=0",
        "-I" + str(include), "-I" + str(generated),
        "-I" + str(OUT / "include/configd"),
        "-I" + str(OUT / "include/iokit-client"),
        "-I" + str(OUT / "include/security"),
        "-I" + str(source / "bootplib"),
        "-I" + str(source / "IPConfiguration.bproj"),
        "-I" + str(source / "ipconfiglib"),
        "-idirafter", str(bsm), "-idirafter", str(bsm / "sys"),
        "-Wno-deprecated-declarations", "-Wno-deprecated-non-prototype",
    ]

    def compile(path, extra=()):
        relative = path.relative_to(source)
        return compile_source(path, OUT / "obj/ipconfiguration" / (str(relative) + ".o"),
            [*flags, *extra])

    event = compile(source / "IPConfiguration.bproj/FDSet.c")
    bootplib = [compile(source / "bootplib" / name) for name in BOOTPLIB]
    library = OUT / "lib/libbootp.a"
    archive(library, [*bootplib, event])
    objects = [compile(source / "IPConfiguration.bproj" / name) for name in PLUGIN]
    objects.append(compile_source(interface["server"], OUT / "obj/ipconfiguration/ipconfigServer.o",
        [*flags, "-DMIG_SERVER_ROUTINE="]))
    iokit = prepare_source("iokit_user")
    objects.append(compile_source(iokit / "pwr_mgt.subproj/IOPMLib.c",
        OUT / "obj/ipconfiguration/IOPMLib.o", [*flags, "-I" + str(iokit)]))
    libraries = [library, OUT / "lib/libconfigd_store.a", OUT / "lib/libbsm.a",
        OUT / "system/IOKit", OUT / "system/CoreFoundation"]
    bundle = OUT / "bundles/IPConfiguration.bundle/Contents"
    (bundle / "MacOS").mkdir(parents=True, exist_ok=True)
    exports = generated / "exports"
    exports.write_text("_load\n_start\n_prime\n_stop\n")
    subprocess.run([
        str(LD), "-L" + str(OUT / "system"), "-Z", "-fatal_warnings", "-bundle",
        "-arch", "x86_64", "-macosx_version_min", "10.11", "-no_uuid", "-dead_strip",
        "-exported_symbols_list", str(exports), "-o", str(bundle / "MacOS/IPConfiguration"),
        *map(str, objects), *map(str, libraries), str(OUT / "system/libSystem.B.dylib"),
    ], check=True)
    info = plistlib.loads((source / "IPConfiguration.bproj/Info.plist").read_bytes())
    info.update(CFBundleExecutable="IPConfiguration", CFBundlePackageType="BNDL", CFBundleVersion="15.0.0")
    (bundle / "Info.plist").write_bytes(plistlib.dumps(info))
    client = compile(source / "ipconfig.tproj/client.c")
    user = compile_source(interface["user"], OUT / "obj/ipconfiguration/ipconfigUser.o", flags)
    link_program(OUT / "bin/ipconfig", [client, user], libraries)


if __name__ == "__main__":
    main()
